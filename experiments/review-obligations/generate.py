"""Compile the experiment's closed expression subset to TLA+ and Go."""

import argparse
import json
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent
CONSTANTS = {"MaxCycle", "MaxBatch", "Mutation"}


def expression_type(expr, fields):
    if type(expr) is int and 0 <= expr <= 4:
        return "int"
    if isinstance(expr, str) and expr in fields | CONSTANTS:
        return "int"
    if not isinstance(expr, list) or not expr or not isinstance(expr[0], str):
        raise ValueError(f"unsupported expression: {expr!r}")
    op, *args = expr
    types = [expression_type(arg, fields) for arg in args]
    if op in {"=", "!=", ">", "<"} and types == ["int", "int"]:
        return "bool"
    if op == "+" and types == ["int", "int"]:
        return "int"
    if op in {"and", "or"} and len(types) >= 2 and set(types) == {"bool"}:
        return "bool"
    if op == "if" and len(types) == 3 and types[0] == "bool" and types[1] == types[2]:
        return types[1]
    raise ValueError(f"unsupported operator, arity or types: {expr!r}")


def validate(spec):
    if (not isinstance(spec, dict) or set(spec) != {"schema", "initial", "actions"}
            or type(spec["schema"]) is not int or spec["schema"] != 1):
        raise ValueError("expected schema 1 with initial and actions only")
    initial, actions = spec["initial"], spec["actions"]
    if not isinstance(initial, dict) or not initial or not isinstance(actions, dict) or not actions:
        raise ValueError("initial and actions must be nonempty objects")
    names = set(initial)
    if names & CONSTANTS:
        raise ValueError("state field shadows a constant")
    for name in [*initial, *actions]:
        if not isinstance(name, str) or not re.fullmatch(r"[a-z][A-Za-z0-9]*", name):
            raise ValueError(f"invalid identifier: {name}")
    for value in initial.values():
        if type(value) is not int or not 0 <= value <= 3:
            raise ValueError("initial values must be integers from zero to three")
    for action in actions.values():
        if (not isinstance(action, dict) or set(action) != {"guard", "set"}
                or not isinstance(action["set"], dict) or not action["set"]):
            raise ValueError("an action needs guard and set only")
        if expression_type(action["guard"], names) != "bool":
            raise ValueError("guard must be boolean")
        for field, expr in action["set"].items():
            if field not in names or expression_type(expr, names) != "int":
                raise ValueError("assignment must name an integer state field")
    return spec


def no_duplicates(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate key: {key}")
        result[key] = value
    return result


def load(path):
    return validate(json.loads(path.read_text(), object_pairs_hook=no_duplicates))


def go_name(name):
    return name[0].upper() + name[1:]


def render(expr, language, fields):
    if type(expr) is int:
        return str(expr)
    if isinstance(expr, str):
        if language == "tla":
            return f"s.{expr}" if expr in fields else expr
        return f"s.{go_name(expr)}" if expr in fields else f"b.{expr}"
    op, *args = expr
    rendered = [render(arg, language, fields) for arg in args]
    if op == "if":
        c, a, z = rendered
        if language == "tla":
            return f"(IF {c} THEN {a} ELSE {z})"
        kind = expression_type(expr, set(fields))
        return f"func() {kind} {{ if {c} {{ return {a} }}; return {z} }}()"
    operators = {"=": "=", "!=": "#", ">": ">", "<": "<", "+": "+", "and": "/\\", "or": "\\/"}
    if language == "go":
        operators.update({"=": "==", "!=": "!=", "and": "&&", "or": "||"})
    return "(" + (f" {operators[op]} ").join(rendered) + ")"


def tla(spec):
    fields = spec["initial"]
    initial = ", ".join(f"{k} |-> {v}" for k, v in fields.items())
    guards, updates = [], []
    for event, action in spec["actions"].items():
        guards.append(f'event = "{event}" -> {render(action["guard"], "tla", fields)}')
        assignments = ", ".join(f"!.{key} = {render(value, 'tla', fields)}" for key, value in action["set"].items())
        updates.append(f'event = "{event}" -> [s EXCEPT {assignments}]')
    events = ", ".join(json.dumps(event) for event in spec["actions"])
    return "\n".join([
        "---- MODULE Generated ----", "\\* Generated by generate.py; do not edit.",
        "EXTENDS Naturals", "CONSTANTS MaxCycle, MaxBatch, Mutation",
        f"Initial == [{initial}]", f"Events == {{{events}}}",
        "Enabled(event, s) == CASE " + "\n    [] ".join(guards) + "\n    [] OTHER -> FALSE",
        "Apply(event, s) == CASE " + "\n    [] ".join(updates) + "\n    [] OTHER -> s", "====", "",
    ])


def go(spec):
    fields = spec["initial"]
    lines = ["// Code generated by generate.py; DO NOT EDIT.", "package obligations", "",
             "// Bounds belong to the finite experiment, not the production protocol.",
             "type Bounds struct { MaxCycle, MaxBatch, Mutation int }", "type Member struct {"]
    lines += [f'{go_name(k)} int `json:"{k}"`' for k in fields]
    lines += ["}", "type State []Member", "", "func Initial(members int) State {",
              "if members < 1 || members > 2 { panic(\"experiment supports one or two members\") }",
              "state := make(State, members)", "for i := range members { state[i] = Member{"]
    lines += [f"{go_name(k)}: {v}," for k, v in fields.items()]
    lines += ["} }; return state", "}", "",
              "// Step leaves its input untouched, including on refusal. Assignments read the pre-state.",
              "func Step(state State, member int, event string, b Bounds) (State, bool) {",
              "if len(state) < 1 || len(state) > 2 || member < 0 || member >= len(state) || b.MaxCycle < 1 || b.MaxCycle > 3 || b.MaxBatch < 1 || b.MaxBatch > 3 || b.Mutation < 0 || b.Mutation > 4 { return state, false }",
              "s := state[member]", "n := s", "switch event {"]
    for event, action in spec["actions"].items():
        lines += [f"case {json.dumps(event)}:", f'if !{render(action["guard"], "go", fields)} {{ return state, false }}']
        lines += [f"n.{go_name(k)} = {render(v, 'go', fields)}" for k, v in action["set"].items()]
    lines += ["default: return state, false", "}", "result := append(State(nil), state...)",
              "result[member] = n", "return result, true", "}", ""]
    return subprocess.run(["gofmt"], input="\n".join(lines), text=True, capture_output=True, check=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = load(ROOT / "transitions.json")
    for name, content in {"Generated.tla": tla(spec), "generated.go": go(spec)}.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"stale generated file: {path}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
